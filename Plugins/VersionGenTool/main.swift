import Extensions
import Foundation

guard CommandLine.arguments.count >= 3 else {
  fputs("Usage: VersionGenTool <output-file> <repo-dir>\n", stderr)
  exit(1)
}

let outputPath = CommandLine.arguments[1]
let repoDir = CommandLine.arguments[2]

let process = Process()
process.executableURL = URL(fileURLWithPath: "/usr/bin/git")
process.arguments = ["-C", repoDir, "describe", "--tags", "--always", "--dirty"]
let pipe = Pipe()
process.standardOutput = pipe
try? process.run()
process.waitUntilExit()

let data = pipe.fileHandleForReading.readDataToEndOfFile()
var version = String(data: data, encoding: .utf8)?.trimmed ?? ""
if version.hasPrefix("v") {
  version = String(version.dropFirst())
}

if version.isEmpty {
  let revProcess = Process()
  revProcess.executableURL = URL(fileURLWithPath: "/usr/bin/git")
  revProcess.arguments = ["-C", repoDir, "rev-parse", "--short", "HEAD"]
  let revPipe = Pipe()
  revProcess.standardOutput = revPipe
  try? revProcess.run()
  revProcess.waitUntilExit()
  let revData = revPipe.fileHandleForReading.readDataToEndOfFile()
  version = String(data: revData, encoding: .utf8)?.trimmed ?? ""
}

if !version.contains(".") {
  version = "1.0.0-\(version)"
}

let clean = version.trimmingCharacters(in: CharacterSet(charactersIn: "vV"))
let parts = clean.split(separator: ".")
guard parts.count >= 2,
  let major = Int(parts[0]),
  let minor = Int(parts[1])
else {
  fputs("VersionGenTool: Failed to parse semantic version components from '\(version)'.\n", stderr)
  exit(1)
}

let patch: Int
if parts.count >= 3 {
  guard let patchPart = parts[2].split(whereSeparator: { $0 == "-" || $0 == "+" }).first,
    let p = Int(patchPart)
  else {
    fputs("VersionGenTool: Failed to parse patch component from '\(parts[2])'.\n", stderr)
    exit(1)
  }
  patch = p
} else {
  patch = 0
}

let content = """
  // AUTO-GENERATED BY VersionPlugin. DO NOT EDIT.
  import Foundation

  public enum EngineVersion {
    public static let current: String = "\(version)"
    public static let semver: Semver = Semver(major: \(major), minor: \(minor), patch: \(patch))
    public static let defaultRange: String = "^\(version)"
  }
  """

try content.write(to: URL(fileURLWithPath: outputPath), atomically: true, encoding: .utf8)
